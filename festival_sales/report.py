"""Compute headline findings from the cleaned data and render them as Markdown."""

from __future__ import annotations

import numpy as np
import pandas as pd

from . import analysis

MARITAL = {0: "unmarried", 1: "married"}


def _top(table: pd.DataFrame, key: str) -> tuple[str, int, float]:
    row = table.iloc[0]
    return row[key], int(row["amount"]), float(row["amount_share_pct"])


def compute_findings(df: pd.DataFrame) -> dict:
    if df.empty:
        raise ValueError("no rows to analyse")
    states = analysis.by_state(df)
    zones = analysis.by_zone(df)
    genders = analysis.by_gender(df)
    ages = analysis.by_age_group(df)
    occupations = analysis.by_occupation(df)
    categories = analysis.by_category(df)
    marital = analysis.marital_status_by_gender(df)
    state_orders = analysis.top_n(df, "state", 1, metric="orders").iloc[0]
    products = analysis.top_products(df, 5)
    return {
        "totals": analysis.overall_totals(df),
        "states": states,
        "zones": zones,
        "genders": genders,
        "ages": ages,
        "occupations": occupations,
        "categories": categories,
        "marital": marital,
        "top_state": _top(states, "state"),
        "top_state_by_orders": (state_orders["state"], int(state_orders["orders"])),
        "top3_states_share": float(states["amount_share_pct"].head(3).sum()),
        "top_zone": _top(zones, "zone"),
        "top_gender": _top(genders, "gender"),
        "top_age_group": _top(ages, "age_group"),
        "top_occupation": _top(occupations, "occupation"),
        "top_category": _top(categories, "product_category"),
        "top3_categories_share": float(categories["amount_share_pct"].head(3).sum()),
        "top_products": products,
    }


def _money(value: int) -> str:
    return f"{value:,}"


def _fmt(value) -> str:
    if isinstance(value, (int, np.integer)):
        return _money(int(value))
    if isinstance(value, (float, np.floating)):
        return f"{value:.2f}"
    return str(value)


def _table(frame: pd.DataFrame, columns: list[str], headers: list[str]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for _, row in frame[columns].iterrows():
        cells = [_fmt(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_markdown(f: dict, rows_dropped: int = 0) -> str:
    t = f["totals"]
    ts, ta, tg = f["top_state"], f["top_age_group"], f["top_gender"]
    gender_names = {"F": "Women", "M": "Men"}
    by_gender = f["genders"].set_index("gender")
    other = "M" if tg[0] == "F" else "F"
    marital = f["marital"].copy()
    marital["segment"] = [
        f"{MARITAL[m]} {'women' if g == 'F' else 'men'}"
        for m, g in zip(marital["marital_status"], marital["gender"])
    ]
    best_segment = marital.iloc[0]
    parts = [
        "# Findings",
        "",
        "Generated by `python -m festival_sales report` from the cleaned data. Amounts are in the "
        "currency units of the source file (the file does not name a currency).",
        "",
        f"The analysis covers {_money(t['transactions'])} transactions from "
        f"{_money(t['customers'])} distinct user ids, {_money(t['orders'])} orders and a total "
        f"amount of {_money(t['amount'])}. {rows_dropped} rows were dropped during cleaning.",
        "",
        "## Headlines",
        "",
        f"- Top state by amount: {ts[0]} with {_money(ts[1])} ({ts[2]:.2f}% of the total). "
        f"The top three states together account for {f['top3_states_share']:.2f}%.",
        f"- Top state by number of orders: {f['top_state_by_orders'][0]} "
        f"with {_money(f['top_state_by_orders'][1])} orders.",
        f"- Top zone: {f['top_zone'][0]} with {_money(f['top_zone'][1])} "
        f"({f['top_zone'][2]:.2f}%).",
        f"- {gender_names[tg[0]]} spent the most: {_money(tg[1])} ({tg[2]:.2f}%). "
        f"{gender_names[other]} spent {_money(int(by_gender.loc[other, 'amount']))}.",
        f"- Top age group: {ta[0]} with {_money(ta[1])} ({ta[2]:.2f}%).",
        f"- Top occupation: {f['top_occupation'][0]} with {_money(f['top_occupation'][1])} "
        f"({f['top_occupation'][2]:.2f}%).",
        f"- Top product category: {f['top_category'][0]} with {_money(f['top_category'][1])} "
        f"({f['top_category'][2]:.2f}%). The top three categories make up "
        f"{f['top3_categories_share']:.2f}%.",
        f"- Biggest marital status and gender segment: {best_segment['segment']} with "
        f"{_money(int(best_segment['amount']))} ({best_segment['amount_share_pct']:.2f}%).",
        "",
        "## Sales by state (top 10)",
        "",
        _table(
            f["states"].head(10),
            ["state", "orders", "amount", "amount_share_pct"],
            ["State", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Sales by zone",
        "",
        _table(
            f["zones"],
            ["zone", "orders", "amount", "amount_share_pct"],
            ["Zone", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Sales by age group",
        "",
        _table(
            f["ages"],
            ["age_group", "orders", "amount", "amount_share_pct"],
            ["Age group", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Sales by product category",
        "",
        _table(
            f["categories"],
            ["product_category", "orders", "amount", "amount_share_pct"],
            ["Category", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Sales by occupation",
        "",
        _table(
            f["occupations"],
            ["occupation", "orders", "amount", "amount_share_pct"],
            ["Occupation", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Marital status and gender",
        "",
        _table(
            marital,
            ["segment", "orders", "amount", "amount_share_pct"],
            ["Segment", "Orders", "Amount", "Share %"],
        ),
        "",
        "## Top 5 products by orders",
        "",
        _table(
            f["top_products"], ["product_id", "orders", "amount"], ["Product", "Orders", "Amount"]
        ),
        "",
        "These figures describe this dataset only. It is one festival season with no dates or "
        "order ids, so nothing here says anything about causes or other years.",
        "",
    ]
    return "\n".join(parts)
